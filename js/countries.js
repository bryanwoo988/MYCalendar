// Map-like accessor matching holidaysFor() in data.js.
export function countryHolidays(cc) {
  const all = (DATA[cc] || []).map(([date, en, zh, kind]) => ({
    date, name: en, names: { en, zh, ms: en }, kind: { h: "official", r: "replacement", b: "bridge", s: "regional", u: "unconfirmed", w: "workday" }[kind],
  }));
  const byYear = new Map();
  for (const h of all) {
    const y = Number(h.date.slice(0, 4));
    if (!byYear.has(y)) byYear.set(y, new Map());
    const m = byYear.get(y);
    m.set(h.date, [...(m.get(h.date) || []), h]);
  }
  const year = (y) => byYear.get(y) || new Map();
  return {
    get: (key) => year(Number(key.slice(0, 4))).get(key),
    has: (key) => (year(Number(key.slice(0, 4))).get(key) || []).some((h) => h.kind !== "workday"),
    year,
    list: (y) => [...year(y).values()].flat(),
  };
}

